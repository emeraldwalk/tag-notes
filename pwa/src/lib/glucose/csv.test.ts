import { describe, expect, it } from 'vitest';
import { InvalidGlucoseCsvError, parseLibreViewCsv } from './csv';

const ZONE = 'America/Chicago';
const META = 'Glucose Data,Generated on,11-26-2026 02:52 AM UTC,Generated by,Test Person';
const HEADERS =
  'Device,Serial Number,Device Timestamp,Record Type,Historic Glucose mg/dL,Scan Glucose mg/dL,Non-numeric Rapid-Acting Insulin,Rapid-Acting Insulin (units),Notes';

/** A synthetic export: rows as [timestamp, type, historic, scan]. */
function csv(rows: [string, number, string?, string?][], { eol = '\r\n', headers = HEADERS } = {}): string {
  const lines = rows.map(([t, type, hist = '', scan = '']) => `Libre app,serial-1,${t},${type},${hist},${scan},,,`);
  return [META, headers, ...lines, ''].join(eol);
}

const parse = (text: string) => parseLibreViewCsv(text, ZONE);

describe('parseLibreViewCsv', () => {
  it('maps record types 0 and 1 to historic and scan, converting local time to UTC', () => {
    const r = parse(
      csv([
        ['01-15-2026 08:00 AM', 0, '120'], // CST, UTC−6
        ['07-15-2026 08:00 AM', 0, '130'], // CDT, UTC−5
        ['07-15-2026 08:03 AM', 1, '', '135'],
      ]),
    );
    expect(r.readings).toEqual([
      { ts: '2026-01-15T14:00:00Z', mgDl: 120, kind: 'historic' },
      { ts: '2026-07-15T13:00:00Z', mgDl: 130, kind: 'historic' },
      { ts: '2026-07-15T13:03:00Z', mgDl: 135, kind: 'scan' },
    ]);
    expect(r).toMatchObject({ historic: 2, scans: 1, skipped: 0, ignored: 0, first: '2026-01-15T14:00:00Z', last: '2026-07-15T13:03:00Z' });
  });

  it('reads 12 AM as midnight and 12 PM as noon', () => {
    const r = parse(csv([['01-15-2026 12:05 AM', 0, '100'], ['01-15-2026 12:05 PM', 0, '101']]));
    expect(r.readings.map((x) => x.ts)).toEqual(['2026-01-15T06:05:00Z', '2026-01-15T18:05:00Z']);
  });

  it('ignores other record types and skips unusable values', () => {
    const r = parse(
      csv([
        ['01-15-2026 08:00 AM', 4],
        ['01-15-2026 08:01 AM', 5],
        ['01-15-2026 08:02 AM', 6],
        ['01-15-2026 08:05 AM', 0, ''],
        ['01-15-2026 08:10 AM', 0, 'HI'],
        ['01-15-2026 08:15 AM', 0, '12'],
        ['01-15-2026 08:20 AM', 1, '150', ''], // a scan's value is in the Scan column
        ['01-15-2026 08:25 AM', 0, '150'],
      ]),
    );
    expect(r).toMatchObject({ historic: 1, scans: 0, ignored: 3, skipped: 4 });
  });

  it('finds columns by header name, accepts LF and a BOM', () => {
    const headers = 'Record Type,Scan Glucose mg/dL,Device Timestamp,Historic Glucose mg/dL';
    const text = `﻿${META}\n${headers}\n0,,01-15-2026 08:00 AM,120\n1,125,01-15-2026 08:01 AM,\n`;
    expect(parse(text).readings).toEqual([
      { ts: '2026-01-15T14:00:00Z', mgDl: 120, kind: 'historic' },
      { ts: '2026-01-15T14:01:00Z', mgDl: 125, kind: 'scan' },
    ]);
  });

  it('skips a local time that does not exist (spring forward)', () => {
    const r = parse(csv([['03-08-2026 01:57 AM', 0, '100'], ['03-08-2026 02:30 AM', 0, '101'], ['03-08-2026 03:02 AM', 0, '102']]));
    expect(r.readings.map((x) => x.ts)).toEqual(['2026-03-08T07:57:00Z', '2026-03-08T08:02:00Z']);
    expect(r.skipped).toBe(1);
  });

  it('gives the two rows of a fall-back time the earlier and then the later instant', () => {
    const r = parse(csv([['11-01-2026 01:30 AM', 0, '200'], ['11-01-2026 01:30 AM', 0, '210'], ['11-01-2026 02:00 AM', 0, '220']]));
    expect(r.readings).toEqual([
      { ts: '2026-11-01T06:30:00Z', mgDl: 200, kind: 'historic' },
      { ts: '2026-11-01T07:30:00Z', mgDl: 210, kind: 'historic' },
      { ts: '2026-11-01T08:00:00Z', mgDl: 220, kind: 'historic' },
    ]);
  });

  it('keeps one reading per time: duplicates collapse, and a historic reading wins over a scan', () => {
    const r = parse(
      csv([
        ['01-15-2026 08:00 AM', 1, '', '130'],
        ['01-15-2026 08:00 AM', 0, '120'],
        ['01-15-2026 08:05 AM', 0, '121'],
        ['01-15-2026 08:05 AM', 1, '', '131'],
        ['01-15-2026 08:07 AM', 1, '', '140'],
        ['01-15-2026 08:07 AM', 1, '', '141'],
      ]),
    );
    expect(r.readings).toEqual([
      { ts: '2026-01-15T14:00:00Z', mgDl: 120, kind: 'historic' },
      { ts: '2026-01-15T14:05:00Z', mgDl: 121, kind: 'historic' },
      { ts: '2026-01-15T14:07:00Z', mgDl: 140, kind: 'scan' },
    ]);
    expect(r.skipped).toBe(3);
  });

  it('sorts by time whatever the file order', () => {
    const r = parse(csv([['07-15-2026 08:00 AM', 0, '130'], ['01-15-2026 08:00 AM', 0, '120']]));
    expect(r.readings.map((x) => x.mgDl)).toEqual([120, 130]);
  });

  it.each([
    ['not an export', 'Device,Serial Number\r\n', /Glucose Data/],
    ['a missing column', csv([], { headers: 'Device,Device Timestamp,Record Type,Historic Glucose mg/dL' }), /Scan Glucose mg\/dL/],
    ['an mmol/L export', csv([], { headers: 'Device Timestamp,Record Type,Historic Glucose mmol/L,Scan Glucose mmol/L' }), /mmol\/L/],
    ['another date format', csv([['2026-01-15 08:00', 0, '120']]), /Line 3/],
  ])('rejects %s', (_name, text, message) => {
    expect(() => parse(text)).toThrow(InvalidGlucoseCsvError);
    expect(() => parse(text)).toThrow(message);
  });

  it('rejects an unknown time zone', () => {
    expect(() => parseLibreViewCsv(csv([]), 'Mars/Olympus')).toThrow(InvalidGlucoseCsvError);
  });
});
